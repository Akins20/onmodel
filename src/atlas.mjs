import { blit } from "./key.mjs";
import { packedVector2 } from "./silhouette.mjs";

/**
 * The atlas: one action per row, every frame the same size, so a CSS steps()
 * animation can walk a row and a game can index frames by number. With it, the
 * metadata engines read: the TexturePacker JSON hash with Aseprite's frame tags
 * and durations (what Phaser, PixiJS, Godot's importers and most others take), a
 * CSS sheet with a keyframe animation per action, and a C header with the frame
 * table and a tiny player, for raylib and anything else that speaks C.
 */

const blank = (width, height) => ({ width, height, data: new Uint8Array(width * height * 4) });

/**
 * Lays actions out one per row. `actions` is [{ name, frames: [image], fps }],
 * every image the same width and height. Returns the atlas image, each frame's
 * placement in order, and each action's range of frame numbers.
 */
export function packActions(actions, { padding = 0 } = {}) {
  if (!actions.length || !actions[0].frames.length) throw new Error("an atlas needs at least one action with one frame");
  const fw = actions[0].frames[0].width;
  const fh = actions[0].frames[0].height;
  for (const a of actions) for (const f of a.frames) if (f.width !== fw || f.height !== fh) throw new Error(`every frame must be ${fw}x${fh}; ${a.name} has a ${f.width}x${f.height} frame`);
  const columns = Math.max(...actions.map((a) => a.frames.length));
  const width = columns * (fw + padding) - padding;
  const height = actions.length * (fh + padding) - padding;
  if (width > 8192 || height > 8192) throw new Error(`the atlas would be ${width}x${height}; keep it under 8192 on a side`);
  const image = blank(width, height);
  const placements = [];
  const ranges = [];
  let index = 0;
  actions.forEach((a, row) => {
    const from = index;
    a.frames.forEach((f, col) => {
      const x = col * (fw + padding);
      const y = row * (fh + padding);
      blit(image, f, x, y);
      placements.push({ name: `${a.name}_${col}`, action: a.name, index, x, y, width: fw, height: fh, durationMs: Math.round(1000 / (a.fps ?? 8)) });
      index++;
    });
    ranges.push({ name: a.name, from, to: index - 1, fps: a.fps ?? 8, row, loop: a.loop !== false });
  });
  return { image, placements, ranges, frame: { width: fw, height: fh }, columns, rows: actions.length };
}

/**
 * The TexturePacker JSON hash, with Aseprite's frameTags and per-frame durations.
 *
 * A trimmed frame says where its pixels sat in the cell (spriteSourceSize) and how big
 * the cell was (sourceSize), which is what Phaser and PixiJS use to draw it unmoved. A
 * pivot is written only when asked for: once it is there Phaser sets each frame's origin
 * from it on every animation frame, overriding any setOrigin in the game's own code, so
 * it is not something to switch on behind anyone's back. It goes in as both `pivot`
 * (Phaser) and `anchor` (PixiJS), normalised to the cell.
 */
export function atlasJSON(atlas, { file = "atlas.png", app = "onmodel", version, pivot = null } = {}) {
  const frames = {};
  for (const p of atlas.placements) {
    const t = p.trim;
    frames[p.name] = {
      frame: { x: p.x, y: p.y, w: p.width, h: p.height },
      rotated: false,
      trimmed: Boolean(t),
      spriteSourceSize: t ? { x: t.x, y: t.y, w: p.width, h: p.height } : { x: 0, y: 0, w: p.width, h: p.height },
      sourceSize: t ? { w: t.sourceW, h: t.sourceH } : { w: p.width, h: p.height },
      duration: p.durationMs,
    };
    if (pivot) {
      const w = t ? t.sourceW : p.width;
      const h = t ? t.sourceH : p.height;
      const at = { x: Math.round((pivot.x / w) * 10000) / 10000, y: Math.round((pivot.y / h) * 10000) / 10000 };
      frames[p.name].pivot = at;
      frames[p.name].anchor = { ...at };
    }
  }
  return {
    frames,
    meta: {
      app,
      version,
      image: file,
      format: "RGBA8888",
      size: { w: atlas.image.width, h: atlas.image.height },
      scale: "1",
      frameTags: atlas.ranges.map((r) => ({ name: r.name, from: r.from, to: r.to, direction: "forward", fps: r.fps })),
    },
  };
}

const cssName = (s) => String(s).replace(/[^a-zA-Z0-9_-]+/g, "-");

/** A stylesheet: a base class for the sprite and a steps() animation per action along its row. */
export function atlasCSS(atlas, { file = "atlas.png", prefix = "om", pixelated = true } = {}) {
  const { width: fw, height: fh } = atlas.frame;
  const lines = [
    `/* Generated by onmodel. One action per row of ${file}; frames ${fw}x${fh}. */`,
    `.${prefix}-sprite { width: ${fw}px; height: ${fh}px; background: url("${file}") no-repeat 0 0;${pixelated ? " image-rendering: pixelated;" : ""} }`,
  ];
  for (const r of atlas.ranges) {
    const n = r.to - r.from + 1;
    const y = -r.row * fh;
    const name = `${prefix}-${cssName(r.name)}`;
    const seconds = Math.round((n / r.fps) * 1000) / 1000;
    lines.push(`.${name} { background-position: 0px ${y}px; animation: ${name} ${seconds}s steps(${n}) infinite; }`);
    lines.push(`@keyframes ${name} { from { background-position: 0px ${y}px; } to { background-position: ${-n * fw}px ${y}px; } }`);
  }
  return lines.join("\n") + "\n";
}

const cName = (s) =>
  String(s)
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, "_")
    .replace(/^_|_$/g, "") || "ACTION";

/** A C header: the frame table, the action table, an enum, and a player that picks the frame for a time. */
export function atlasHeader(atlas, { file = "atlas.png", guard = "OM_ATLAS_H", prefix = "OM", pivot = null } = {}) {
  const { width: fw, height: fh } = atlas.frame;
  // C convention: types in CamelCase (OmFrame), constants and macros in capitals (OM_FRAMES).
  const Type = prefix[0].toUpperCase() + prefix.slice(1).toLowerCase();
  const trimmed = atlas.placements.some((p) => p.trim);
  const frames = atlas.placements
    .map((p) => (trimmed ? `    { ${p.x}, ${p.y}, ${p.width}, ${p.height}, ${p.trim?.x ?? 0}, ${p.trim?.y ?? 0}, ${p.trim?.sourceW ?? p.width}, ${p.trim?.sourceH ?? p.height} }` : `    { ${p.x}, ${p.y}, ${p.width}, ${p.height} }`))
    .join(",\n");
  const extra = [];
  if (trimmed) {
    extra.push(
      "",
      "/* Trimmed: each frame holds only its own pixels. Draw one with its top left at",
      " * (cell x + ox, cell y + oy), where the cell is FRAME_W by FRAME_H; with raylib:",
      " *   DrawTextureRec(tex, (Rectangle){ (float)f->x, (float)f->y, (float)f->w, (float)f->h },",
      " *                  (Vector2){ (float)(cx + f->ox), (float)(cy + f->oy) }, WHITE); */",
      `#define ${prefix}_TRIMMED 1`,
    );
  }
  if (pivot) {
    extra.push("", `/* The point that stays put from frame to frame, in cell pixels: put it on the character's position. */`, `static const float ${prefix}_PIVOT_X = ${Number(pivot.x).toFixed(1)}f;`, `static const float ${prefix}_PIVOT_Y = ${Number(pivot.y).toFixed(1)}f;`);
  }
  const actions = atlas.ranges.map((r) => `    { "${r.name}", ${r.from}, ${r.to}, ${r.fps.toFixed(1)}f }`).join(",\n");
  const names = atlas.ranges.map((r, i) => `    ${prefix}_${cName(r.name)} = ${i}`).join(",\n");
  return `/* Generated by onmodel. Frames of ${file}, each ${fw}x${fh}${trimmed ? " before trimming" : ", one action per row"}. */
#ifndef ${guard}
#define ${guard}

typedef struct { int x, y, w, h${trimmed ? ", ox, oy, sw, sh" : ""}; } ${Type}Frame;
typedef struct { const char *name; int from, to; float fps; } ${Type}Action;

static const int ${prefix}_FRAME_W = ${fw};
static const int ${prefix}_FRAME_H = ${fh};
static const int ${prefix}_FRAME_COUNT = ${atlas.placements.length};
static const int ${prefix}_ACTION_COUNT = ${atlas.ranges.length};${extra.join("\n")}

static const ${Type}Frame ${prefix}_FRAMES[${atlas.placements.length}] = {
${frames}
};

static const ${Type}Action ${prefix}_ACTIONS[${atlas.ranges.length}] = {
${actions}
};

enum {
${names}
};

/* The frame of an action at time t seconds, looping. */
static inline int ${prefix.toLowerCase()}_frame_at(const ${Type}Action *a, float t) {
    int n = a->to - a->from + 1;
    int i = (int)(t * a->fps) % n;
    if (i < 0) i += n;
    return a->from + i;
}

#endif
`;
}

/**
 * A Godot 4 SpriteFrames resource: one animation per action, each frame an AtlasTexture
 * cut out of the sheet, so the engine reads the atlas directly with no importer and no
 * plugin.
 *
 * The shape here is not from memory. Godot 4.7.2 was asked to build this resource and
 * save it, and what it wrote is what this reproduces, which caught two things worth
 * knowing: `loop` is written as 1 or 0 rather than true or false, and a frame's
 * `duration` is a multiple of the animation's own speed rather than a time, so uniform
 * frames are 1.0 and the speed carries the frames per second.
 *
 * Godot gives its sub-resources random ids. These are numbered instead, so the same
 * sprites produce the same file and a diff shows what actually changed.
 */
export function atlasGodot(atlas, { file = "atlas.png", resPath = null, normal = null, filter = null } = {}) {
  const texture = resPath ?? `res://${file}`;
  const lines = [`[gd_resource type="SpriteFrames" format=3]`, "", `[ext_resource type="Texture2D" path="${texture}" id="1_atlas"]`];
  // An AtlasTexture may take a CanvasTexture as its atlas, which Godot 4.7.2 confirmed by
  // saving and loading the chain back. That is worth doing: it carries the normal map and
  // the filtering INSIDE the resource, so a sprite lights correctly and pixel art stays
  // crisp with nothing to set on the node. Godot 4 has no filter setting in a .import, so
  // this is the only place it can travel with the art.
  const wrapped = Boolean(normal || filter != null);
  if (normal) lines.push(`[ext_resource type="Texture2D" path="${normal}" id="2_normal"]`);
  lines.push("");
  if (wrapped) {
    lines.push(`[sub_resource type="CanvasTexture" id="CanvasTexture_0"]`, `diffuse_texture = ExtResource("1_atlas")`);
    if (normal) lines.push(`normal_texture = ExtResource("2_normal")`);
    if (filter != null) lines.push(`texture_filter = ${filter}`);
    lines.push("");
  }
  const source = wrapped ? `SubResource("CanvasTexture_0")` : `ExtResource("1_atlas")`;
  // A trimmed frame's margin puts it back in its cell: where its pixels sat, and how much
  // was cut on each axis. Godot 4.7.2 wrote it as the line after region, then drew a
  // hand-written one back at the full cell size and identical to it pixel for pixel.
  for (const p of atlas.placements) {
    lines.push(`[sub_resource type="AtlasTexture" id="AtlasTexture_${p.index}"]`, `atlas = ${source}`, `region = Rect2(${p.x}, ${p.y}, ${p.width}, ${p.height})`);
    const t = p.trim;
    if (t && (t.x || t.y || t.sourceW !== p.width || t.sourceH !== p.height)) lines.push(`margin = Rect2(${t.x}, ${t.y}, ${t.sourceW - p.width}, ${t.sourceH - p.height})`);
    lines.push("");
  }
  const animations = atlas.ranges.map((r) => {
    const frames = [];
    for (let i = r.from; i <= r.to; i++) frames.push(`{\n"duration": 1.0,\n"texture": SubResource("AtlasTexture_${i}")\n}`);
    return `{\n"frames": [${frames.join(", ")}],\n"loop": ${r.loop === false ? 0 : 1},\n"name": &"${String(r.name).replace(/"/g, "")}",\n"speed": ${Number(r.fps ?? 8).toFixed(1)}\n}`;
  });
  lines.push("[resource]", `animations = [${animations.join(", ")}]`, "");
  return lines.join("\n");
}

/**
 * A Godot 4 TileSet: an atlas source over the image, with every cell of the grid
 * declared as a tile. Taken from what Godot 4.7.2 itself wrote, not from memory; a tile
 * is declared by the line `<column>:<row>/0 = 0`, and leaving it out leaves the cell
 * empty in the editor however good the pixels are.
 */
export function atlasTileSet(image, { file = "tiles.png", resPath = null, tileWidth = 32, tileHeight = tileWidth, collision = null, occluder = null, terrain = null } = {}) {
  const texture = resPath ?? `res://${file}`;
  const columns = Math.max(1, Math.floor(image.width / tileWidth));
  const rows = Math.max(1, Math.floor(image.height / tileHeight));
  // A tile's collision points are measured from the CENTRE of the tile, not its corner.
  // Godot 4.7.2 wrote -16,-16 to 16,16 for a 32 px tile; written from the corner, the body
  // would sit half a tile down and to the right of the art it belongs to.
  const centre = { originX: tileWidth / 2, originY: tileHeight / 2 };
  const head = [`[gd_resource type="TileSet" format=3]`, "", `[ext_resource type="Texture2D" path="${texture}" id="1_atlas"]`, ""];
  if (occluder) head.push(`[sub_resource type="OccluderPolygon2D" id="OccluderPolygon2D_0"]`, `polygon = ${packedVector2(occluder, centre)}`, "");
  const cells = [];
  // With a terrain set, only the cells it names are declared, each carrying the peering
  // bits that tell a TileMapLayer which neighbours it fits against. Without one, every
  // cell of the grid is declared as a plain tile.
  const grid = terrain ? terrain.cells.map((c) => [c.col, c.row, c]) : [];
  if (!terrain) for (let y = 0; y < rows; y++) for (let x = 0; x < columns; x++) grid.push([x, y, null]);
  for (const [x, y, t] of grid) {
    cells.push(`${x}:${y}/0 = 0`);
    if (t) {
      cells.push(`${x}:${y}/0/terrain_set = 0`, `${x}:${y}/0/terrain = 0`);
      for (const bit of t.bits) cells.push(`${x}:${y}/0/terrains_peering_bit/${bit} = 0`);
    }
    if (occluder) cells.push(`${x}:${y}/0/occlusion_layer_0/polygon_0/polygon = SubResource("OccluderPolygon2D_0")`);
    if (collision) cells.push(`${x}:${y}/0/physics_layer_0/polygon_0/points = ${packedVector2(collision, centre)}`);
  }
  const layers = [];
  if (occluder) layers.push("occlusion_layer_0/light_mask = 1");
  if (collision) layers.push("physics_layer_0/collision_layer = 1");
  if (terrain) {
    const c = terrain.color ?? [0.4, 0.7, 0.4];
    layers.push(`terrain_set_0/mode = ${terrain.mode}`, `terrain_set_0/terrain_0/name = "${String(terrain.name ?? "terrain").replace(/"/g, "")}"`, `terrain_set_0/terrain_0/color = Color(${c[0]}, ${c[1]}, ${c[2]}, 1)`);
  }
  return [
    ...head,
    `[sub_resource type="TileSetAtlasSource" id="TileSetAtlasSource_0"]`,
    `texture = ExtResource("1_atlas")`,
    `texture_region_size = Vector2i(${tileWidth}, ${tileHeight})`,
    ...cells,
    "",
    "[resource]",
    `tile_size = Vector2i(${tileWidth}, ${tileHeight})`,
    ...layers,
    `sources/0 = SubResource("TileSetAtlasSource_0")`,
    "",
  ].join("\n");
}

/**
 * A Godot 4 CanvasTexture: the colour and the normal map bound together, which is how a
 * Light2D is told which way each pixel of a sprite faces. Taken from what Godot 4.7.2
 * wrote, including the enum values, which are the part a guess gets wrong:
 * `texture_filter` 1 is nearest and `texture_repeat` 2 is enabled, not 1.
 */
export function atlasCanvasTexture({ diffuse, normal = null, specular = null, filter = null, repeat = null, shininess = null } = {}) {
  const ext = [`[ext_resource type="Texture2D" path="${diffuse}" id="1_diffuse"]`];
  const body = [`diffuse_texture = ExtResource("1_diffuse")`];
  let n = 2;
  if (normal) {
    ext.push(`[ext_resource type="Texture2D" path="${normal}" id="${n}_normal"]`);
    body.push(`normal_texture = ExtResource("${n}_normal")`);
    n++;
  }
  if (specular) {
    ext.push(`[ext_resource type="Texture2D" path="${specular}" id="${n}_specular"]`);
    body.push(`specular_texture = ExtResource("${n}_specular")`);
    n++;
  }
  if (shininess != null) body.push(`specular_shininess = ${Number(shininess).toFixed(1)}`);
  // 1 is nearest, which pixel art needs; 2 is repeat enabled, which a tile needs.
  if (filter != null) body.push(`texture_filter = ${filter}`);
  if (repeat != null) body.push(`texture_repeat = ${repeat}`);
  return [`[gd_resource type="CanvasTexture" format=3]`, "", ...ext, "", "[resource]", ...body, ""].join("\n");
}

export const GODOT_FILTER_NEAREST = 1;
export const GODOT_REPEAT_ENABLED = 2;

/**
 * A Godot import preset for a PNG, written beside it as `<file>.png.import`.
 *
 * Godot does not load a PNG, it loads the texture its importer made, and those settings
 * decide whether pixel art is blurred, whether it is quietly VRAM-compressed, and whether
 * a normal map is treated as one. A perfect PNG imported wrong looks exactly like a bad
 * PNG, which is the sort of failure this tool exists to stop.
 *
 * Only `[params]` is written. The `[remap]` block holds a uid and a content hash that only
 * Godot can compute, and Godot 4.7.2 was asked what it does with a params-only file: it
 * fills in the rest, keeps every setting given, and leaves the defaults alone. So the
 * preset can be written without reproducing anything that belongs to the engine.
 */
export function godotImport({ pixel = false, normalMap = false } = {}) {
  const params = [
    // Lossless for art. The default can re-encode, and once pixel art has been through a
    // lossy pass no amount of care downstream brings the edges back.
    "compress/mode=0",
    // Mipmaps are for art seen at many sizes in 3D; on a 2D sprite they only soften it.
    "mipmaps/generate=false",
    // Bleeding the edge colour into transparency stops a halo when the art is filtered,
    // and is exactly wrong for pixel art, which is not filtered.
    `process/fix_alpha_border=${pixel ? "false" : "true"}`,
    // The trap worth closing: left at its default, a 2D texture that is ever touched by
    // anything 3D is silently re-imported as VRAM-compressed, and 2D art never recovers.
    "detect_3d/compress_to=0",
  ];
  if (normalMap) {
    params.push("compress/normal_map=1", "process/normal_map_invert_y=false");
  }
  return `[params]\n\n${params.join("\n")}\n`;
}
